"""Evaluation harness for change detection.

Run from the repo root:
    python eval/run.py                              # all configs that can run (Gemini ones need GEMINI_API_KEY)
    python eval/run.py --configs mock,gemini --models gemini-3.5-flash-lite,gemini-2.5-flash

Every label file in eval/labels/*.json is a sample pair with criteria cases and ground-truth boxes.
Each case goes through the real pipeline steps (alignment -> optional heatmap hints -> analysis) and is
scored with greedy IoU matching (eval/metrics.py). Results are printed and written to eval/results.md.
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "eval"))

import cv2  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

from metrics import match, summarize  # noqa: E402

LABELS_DIR = ROOT / "eval" / "labels"
RESULTS = ROOT / "eval" / "results.md"

# name -> (environment overrides, use heatmap hints)
CONFIGS = {
    "mock": ({"MOCK_LLM": "1"}, False),
    "gemini": ({"MOCK_LLM": "0", "ANALYSIS_VERIFY": "1", "ANALYSIS_TILING": "0"}, False),
    "gemini-noverify": ({"MOCK_LLM": "0", "ANALYSIS_VERIFY": "0", "ANALYSIS_TILING": "0"}, False),
    "gemini-tiled": ({"MOCK_LLM": "0", "ANALYSIS_VERIFY": "1", "ANALYSIS_TILING": "1", "ANALYSIS_TILE_MIN_SIDE": "0", "ANALYSIS_TILE_GRID": "2"}, False),
    "gemini-hints": ({"MOCK_LLM": "0", "ANALYSIS_VERIFY": "1", "ANALYSIS_TILING": "0"}, True),
}


def heatmap_hints(img_a, img_b, aligned):
    """Candidate boxes from P1's heatmap module, computed exactly as pipeline.run does."""
    from app.alignment import harmonize_resolution
    from app.diff.heatmap import candidate_boxes, change_heatmap

    diff_a = harmonize_resolution(img_a, aligned.homography, img_b.shape)
    return candidate_boxes(change_heatmap(diff_a, aligned.aligned_b, getattr(aligned, "valid_mask", None)))


def run_config(name: str, labels: list[dict], model: str | None) -> dict:
    from app.alignment import IMREAD_PIXELS, align
    from app.analysis import analyze

    env, use_hints = CONFIGS[name]
    saved = {k: os.environ.get(k) for k in [*env, "GEMINI_MODEL", "ANALYSIS_CACHE"]}
    os.environ.update(env)
    os.environ["ANALYSIS_CACHE"] = "0"  # measure real calls, not cached answers
    if model:
        os.environ["GEMINI_MODEL"] = model
    rows, counts, seconds = [], [], []
    try:
        for label in labels:
            img_a = cv2.imread(str(ROOT / label["image_a"]), IMREAD_PIXELS)
            img_b = cv2.imread(str(ROOT / label["image_b"]), IMREAD_PIXELS)
            aligned = align(img_a, img_b)
            hints = heatmap_hints(img_a, img_b, aligned) if use_hints else None
            for case in label["cases"]:
                start = time.perf_counter()
                try:
                    result = analyze(img_a, aligned.aligned_b, case["criteria"], "en", hints, aligned=aligned.ok)
                    pred = [c.box for c in result.changes]
                    error = ""
                except Exception as e:  # one failing case must not stop the run
                    pred, error = [], str(e)[:80]
                seconds.append(time.perf_counter() - start)
                c = match(pred, case["boxes"])
                counts.append(c)
                rows.append({"pair": label["pair"], "criteria": case["criteria"], "pred": len(pred),
                             "truth": len(case["boxes"]), **c, "error": error})
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
    return {"summary": summarize(counts), "rows": rows, "avg_seconds": sum(seconds) / max(len(seconds), 1)}


def to_markdown(results: dict) -> str:
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python eval/run.py`. Match = IoU >= 0.3 (greedy, one-to-one).",
        "",
        "| Config | Precision | Recall | Mean IoU | TP | FP | FN | Avg s/case |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        s = r["summary"]
        lines.append(f"| {name} | {s['precision']:.2f} | {s['recall']:.2f} | {s['mean_iou']:.2f} | "
                     f"{s['tp']} | {s['fp']} | {s['fn']} | {r['avg_seconds']:.2f} |")
    for name, r in results.items():
        lines += ["", f"## {name}", "", "| Pair | Criteria | Pred | Truth | TP | FP | FN | Error |", "|---|---|---|---|---|---|---|---|"]
        for row in r["rows"]:
            lines.append(f"| {row['pair']} | {row['criteria']} | {row['pred']} | {row['truth']} | "
                         f"{row['tp']} | {row['fp']} | {row['fn']} | {row['error']} |")
    return "\n".join(lines) + "\n"


def main():
    load_dotenv(ROOT / ".env")
    load_dotenv(ROOT / "backend" / ".env")
    p = argparse.ArgumentParser()
    p.add_argument("--configs", default=",".join(CONFIGS), help=f"comma list of {list(CONFIGS)}")
    p.add_argument("--models", default="", help="comma list of Gemini models (default: GEMINI_MODEL)")
    p.add_argument("--out", default=str(RESULTS))
    args = p.parse_args()

    labels = [json.loads(f.read_text(encoding="utf-8")) for f in sorted(LABELS_DIR.glob("*.json"))]
    has_key = bool(os.getenv("GEMINI_API_KEY"))
    models = [m for m in args.models.split(",") if m] or [None]

    results = {}
    for name in args.configs.split(","):
        if name not in CONFIGS:
            raise SystemExit(f"Unknown config {name!r}")
        if name != "mock" and not has_key:
            print(f"skip {name}: no GEMINI_API_KEY")
            continue
        for model in models if name != "mock" else [None]:
            label = f"{name} ({model})" if model else name
            print(f"running {label} ...")
            results[label] = run_config(name, labels, model)
            s = results[label]["summary"]
            print(f"  precision {s['precision']:.2f}  recall {s['recall']:.2f}  mean IoU {s['mean_iou']:.2f}")

    Path(args.out).write_text(to_markdown(results), encoding="utf-8")
    print(f"written {args.out}")


if __name__ == "__main__":
    main()
